#!/usr/bin/env bash
# System-level (root) setup for a DGX OS workstation. Idempotent; re-run any time.
#
#   sudo platforms/dgx/system-setup.sh <hostname> [step...]
#
# <hostname> is gb10-<n>; n picks this node's QSFP addresses (gb10-1 -> .10, gb10-2 -> .11).
# With no steps, runs every default step in order. ssh-harden is never run by default: it
# disables password logins, so run it only after both nodes have exchanged SSH keys.
#
# Steps: hostname apt chrome tailscale docker network terminal cleanup ssh-harden
#
# cleanup also has a dry run that needs no root and changes nothing:
#   DRY_RUN=1 platforms/dgx/system-setup.sh <hostname> cleanup
set -euo pipefail

platform_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo="$(cd "$platform_dir/../.." && pwd)"
source "$repo/lib/platform.sh"
require_platform dgx

DEFAULT_STEPS=(hostname apt chrome tailscale docker network terminal cleanup)

# Both nodes must use the same physical QSFP port (NVIDIA's guidance, for NCCL). Each physical
# port shows up as two logical interfaces; these are port 0's. Override for port 1.
CX7_IFACES=(${CX7_IFACES:-enp1s0f0np0 enP2p1s0f0np0})
CX7_SUBNETS=(192.168.100 192.168.101)
NODE_COUNT=2

hostname_arg="${1:-}"
if [[ ! $hostname_arg =~ ^gb10-([0-9]+)$ ]]; then
  echo "Usage: sudo $0 <gb10-N> [step...]" >&2
  exit 1
fi
node_index="${BASH_REMATCH[1]}"
shift
steps=("$@")
[[ ${#steps[@]} -eq 0 ]] && steps=("${DEFAULT_STEPS[@]}")

if [[ ${DRY_RUN:-} != 1 && $EUID -ne 0 ]]; then
  echo "Run with sudo (or DRY_RUN=1 for a cleanup dry run)." >&2
  exit 1
fi

user="${SUDO_USER:-$(id -un)}"
user_home="$(getent passwd "$user" | cut -d: -f6)"
user_uid="$(id -u "$user")"

step() { printf '\n==> %s\n' "$*"; }

# Run a command as the invoking user inside their desktop session, when one is running.
as_user() {
  sudo -u "$user" env XDG_RUNTIME_DIR="/run/user/$user_uid" \
    DBUS_SESSION_BUS_ADDRESS="unix:path=/run/user/$user_uid/bus" "$@"
}

# QSFP address of node n on the given subnet: gb10-1 -> .10, gb10-2 -> .11, ...
cx7_address() { echo "$1.$((9 + $2))"; }

do_hostname() {
  step "Hostname: gb10-$node_index"
  hostnamectl set-hostname "gb10-$node_index"

  # Ubuntu resolves its own hostname through the 127.0.1.1 line, keeping 127.0.0.1 for localhost
  # alone. DGX OS's first-boot setup also maps 127.0.0.1 to the hostname; drop that duplicate.
  sed -i -E '/^127\.0\.0\.1[[:space:]]+gb10-[0-9]+[[:space:]]*$/d' /etc/hosts
  if grep -q '^127\.0\.1\.1' /etc/hosts; then
    sed -i "s/^127\.0\.1\.1.*/127.0.1.1\tgb10-$node_index/" /etc/hosts
  else
    printf '127.0.1.1\tgb10-%s\n' "$node_index" >>/etc/hosts
  fi

  # QSFP names for every node, so NCCL/MPI hostfiles and ssh can use gb10-N-qsfp. LAN and
  # Tailscale names already resolve through the router and MagicDNS.
  local block="" n
  for ((n = 1; n <= NODE_COUNT; n++)); do
    block+="$(cx7_address "${CX7_SUBNETS[0]}" "$n")"$'\t'"gb10-$n-qsfp"$'\n'
  done
  sed -i '/^# BEGIN dotfiles qsfp$/,/^# END dotfiles qsfp$/d' /etc/hosts
  printf '# BEGIN dotfiles qsfp\n%s# END dotfiles qsfp\n' "$block" >>/etc/hosts
}

do_apt() {
  step "Base packages"
  apt-get update
  # Compilers and archive tools that LazyVim (treesitter parsers, Mason) and mise builds need.
  # xclip is the clipboard tool: DGX OS forces nvidia-drm modeset=0, so GNOME runs on X11 and
  # wl-clipboard (Omarchy's) can't work here. kitty-terminfo lets root and sudo handle SSH sessions
  # from kitty (TERM=xterm-kitty); your user gets kitty's own copy from install.sh.
  apt-get install -y build-essential curl git unzip xclip kitty-terminfo
}

do_chrome() {
  step "Google Chrome"
  if ! dpkg -s google-chrome-stable >/dev/null 2>&1; then
    local tmp
    tmp="$(mktemp -d)"
    curl -fsSL -o "$tmp/chrome.deb" https://dl.google.com/linux/direct/google-chrome-stable_current_arm64.deb
    # The package adds Google's apt repo, so Chrome updates with the rest of the system.
    apt-get install -y "$tmp/chrome.deb"
    rm -rf "$tmp"
  fi
  as_user xdg-settings set default-web-browser google-chrome.desktop ||
    echo "Couldn't set the default browser (no desktop session?); re-run ./install.sh from the desktop."
}

do_tailscale() {
  step "Tailscale"
  command -v tailscale >/dev/null || curl -fsSL https://tailscale.com/install.sh | sh
  if tailscale status >/dev/null 2>&1; then
    echo "Already connected to the tailnet."
  else
    tailscale up --ssh
  fi
}

do_docker() {
  step "Docker group for $user"
  usermod -aG docker "$user"
  echo "Takes effect at next login."
}

do_network() {
  step "QSFP link: static addresses on ${CX7_IFACES[*]}"
  local netplan=/etc/netplan/40-cx7.yaml i
  {
    echo "# QSFP link to the other GB10s. Generated by dotfiles platforms/dgx/system-setup.sh."
    echo "network:"
    echo "  version: 2"
    echo "  ethernets:"
    for i in "${!CX7_IFACES[@]}"; do
      echo "    ${CX7_IFACES[$i]}:"
      echo "      renderer: NetworkManager"
      echo "      dhcp4: false"
      echo "      addresses:"
      echo "        - $(cx7_address "${CX7_SUBNETS[$i]}" "$node_index")/24"
    done
  } >"$netplan"
  chmod 600 "$netplan"

  # NetworkManager gave every ConnectX-7 interface a default DHCP profile. Nothing on the
  # direct cable hands out addresses, so those fail every 45s and spam "Connection failed".
  # Drop them and stop NetworkManager from recreating them.
  cat >/etc/NetworkManager/conf.d/90-cx7-no-auto-default.conf <<'EOF'
# Generated by dotfiles platforms/dgx/system-setup.sh. The ConnectX-7 ports are configured by
# /etc/netplan/40-cx7.yaml; no automatic DHCP profiles for them.
[main]
no-auto-default=interface-name:enp1s0f*,interface-name:enP2p1s0f*
EOF
  # Only the stock "Wired connection N" profiles on ConnectX-7 ports; netplan's own profiles
  # and the onboard LAN port's profile stay.
  local uuid id iface
  while read -r uuid; do
    id="$(nmcli -g connection.id connection show "$uuid")"
    iface="$(nmcli -g connection.interface-name connection show "$uuid")"
    if [[ $id == "Wired connection "* && $iface =~ ^en(p|P2p)1s0f[01]np[01]$ ]]; then
      nmcli connection delete "$uuid"
    fi
  done < <(nmcli -g UUID connection show)

  systemctl reload NetworkManager
  netplan apply
  ip -br addr show | grep -E "$(IFS='|'; echo "${CX7_IFACES[*]}")" || true
}

do_terminal() {
  step "kitty as the default terminal"
  local kitty="$user_home/.local/kitty.app/bin/kitty"
  if [[ ! -x $kitty ]]; then
    echo "kitty isn't installed yet; run ./install.sh first, then re-run this step."
    return
  fi
  update-alternatives --install /usr/bin/x-terminal-emulator x-terminal-emulator "$kitty" 60
  update-alternatives --set x-terminal-emulator "$kitty"
}

# Apps removed by cleanup. On DGX OS these are pulled in by the nvidia-system-station-*
# bundles, so removing any of them removes those bundles too.
CLEANUP_PACKAGES=(
  # Office, media, games
  'libreoffice*' rhythmbox 'rhythmbox-*' shotwell 'shotwell-*' cheese totem 'totem-*' transmission-gtk
  gnome-mahjongg gnome-mines gnome-sudoku aisleriot gkrellm
  # Mail and browser (the debs are transitional wrappers around the snaps)
  thunderbird 'thunderbird-locale-*' firefox 'firefox-locale-*' xul-ext-ubufox
  # Remote desktop, scanning, backup
  remmina 'remmina-*' simple-scan deja-dup
  # Terminal (kitty replaces it)
  gnome-terminal gnome-terminal-data nautilus-extension-gnome-terminal
)
CLEANUP_SNAPS=(thunderbird firefox)

# Bundle dependencies only there for the removed apps; left unmarked so autoremove takes them.
CLEANUP_LEFTOVERS='^(libreoffice-|mythes-|openjdk-8-|firefox-|thunderbird-|rhythmbox|shotwell|totem|remmina|xul-ext-)'

# Nothing matching this may ever be removed by cleanup. The nvidia-system-station-* bundles are
# expected to go (they're app bundles); everything else NVIDIA/DGX, CUDA, Docker, snapd (NVIDIA's
# firmware-updater ships as a snap), networking, SSH and the desktop itself must stay.
PROTECTED='^(nvidia-|dgx-|cuda|libcuda|libnvidia|docker|containerd|snapd|tailscale|openssh|network-manager|netplan|gdm3|gnome-shell|gnome-session|mutter|nautilus$|mlnx|rdma|ibverbs|perftest|ucx|ubuntu-(minimal|server|standard)$|linux-|grub|shim|systemd)'
EXPECTED_BUNDLES='^nvidia-system-station(-apps|-games|-utils)?$'

# Prints the packages an apt-get -s run would remove.
simulated_removals() { apt-get -s "$@" 2>/dev/null | awk '/^Remv /{print $2}'; }

check_protected() {
  local blocked
  blocked="$(grep -E "$PROTECTED" | grep -vE "$EXPECTED_BUNDLES" || true)"
  if [[ -n $blocked ]]; then
    echo "Refusing: this would remove protected packages:" >&2
    echo "$blocked" | sed 's/^/  /' >&2
    exit 1
  fi
}

do_cleanup() {
  step "Cleanup of bundled apps"
  local apt_opts=() sim_dir=""

  if [[ ${DRY_RUN:-} == 1 ]]; then
    # Mark packages in a copy of apt's state so the whole run can be simulated without root.
    sim_dir="$(mktemp -d)"
    cp /var/lib/apt/extended_states "$sim_dir/"
    apt_opts=(-o "Dir::State::extended_states=$sim_dir/extended_states")
    echo "(dry run: nothing will change)"
  fi

  # Keep everything else the bundles provide (Wi-Fi, printing, gparted, eog, evince, ...) by
  # marking it manually installed; without this, autoremove would cascade into ~270 packages.
  local bundles keep
  bundles="$(dpkg-query -W -f '${Package} ${Status}\n' 'nvidia-system-station*' 2>/dev/null |
    awk '/ installed$/{print $1}')"
  if [[ -n $bundles ]]; then
    keep="$(apt-cache depends --installed --no-recommends --no-suggests $bundles 2>/dev/null |
      awk '/Depends:/{print $2}' | grep -v '^<' | sed 's/:arm64$//' | sort -u |
      grep -vE "$CLEANUP_LEFTOVERS" |
      grep -vxF -f <(printf '%s\n' "${CLEANUP_PACKAGES[@]}" | grep -v '\*') || true)"
    # shellcheck disable=SC2086
    [[ -n $keep ]] && apt-mark "${apt_opts[@]}" manual $keep >/dev/null
  fi

  local installed=() p
  for p in "${CLEANUP_PACKAGES[@]}"; do
    while read -r pkg; do installed+=("$pkg"); done < <(
      dpkg-query -W -f '${Package} ${Status}\n' "$p" 2>/dev/null | awk '/ installed$/{print $1}')
  done

  local removals
  removals="$(simulated_removals "${apt_opts[@]}" remove "${installed[@]}")"
  echo "$removals" | check_protected
  echo "Removing $(echo "$removals" | grep -c .) packages:"
  echo "$removals" | column -c 100

  local autoremovals
  if [[ ${DRY_RUN:-} == 1 ]]; then
    # autoremove can't be simulated on top of a simulated remove, so approximate it: what
    # autoremove would take once the removals' reverse dependencies are gone.
    autoremovals="$(simulated_removals "${apt_opts[@]}" remove --autoremove "${installed[@]}" |
      grep -vxF -f <(echo "$removals") || true)"
  else
    apt-get remove -y "${installed[@]}"
    autoremovals="$(simulated_removals autoremove)"
  fi
  echo "$autoremovals" | check_protected
  echo "Autoremoving $(echo "$autoremovals" | grep -c .) leftover dependencies:"
  echo "$autoremovals" | column -c 100

  if [[ ${DRY_RUN:-} == 1 ]]; then
    echo "Snaps that would be removed: ${CLEANUP_SNAPS[*]}"
    rm -rf "$sim_dir"
    return
  fi

  apt-get autoremove -y
  for p in "${CLEANUP_SNAPS[@]}"; do
    snap list "$p" >/dev/null 2>&1 && snap remove --purge "$p"
  done
}

do_ssh_harden() {
  step "OpenSSH: key-only logins"
  if [[ ! -s $user_home/.ssh/authorized_keys ]]; then
    echo "Refusing: $user_home/.ssh/authorized_keys is empty, which would lock out key-less logins." >&2
    echo "Exchange keys between the nodes first (see the README), then re-run this step." >&2
    exit 1
  fi
  cat >/etc/ssh/sshd_config.d/10-key-only.conf <<'EOF'
# Generated by dotfiles platforms/dgx/system-setup.sh. Tailscale SSH is unaffected.
PasswordAuthentication no
KbdInteractiveAuthentication no
PermitRootLogin no
EOF
  sshd -t
  systemctl restart ssh.socket
}

for s in "${steps[@]}"; do
  case "$s" in
    hostname | apt | chrome | tailscale | docker | network | terminal | cleanup) "do_$s" ;;
    ssh-harden) do_ssh_harden ;;
    *)
      echo "Unknown step: $s" >&2
      exit 1
      ;;
  esac
done

printf '\nSystem setup complete.\n'
